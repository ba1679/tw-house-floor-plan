import { readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import type { ReactElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import sharp from "sharp";
import { BrandMark } from "../components/BrandMark";
import { APPLE_TOUCH_ICON_PATH, FAVICON_PATH, OG_IMAGE_PATH } from "../lib/site-metadata";
import { BRAND_IMAGE_ALT, BRAND_PROMISE, SITE_NAME, SITE_PURPOSE, SITE_ROMANIZATION } from "../lib/ui/copy";

async function generateBrandAssets() {
  const css = await readFile("app/brand-tokens.css", "utf8") + await readFile("app/globals.css", "utf8");
  const tokens = new Map([...css.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map((match) => [match[1], match[2].trim()]));

  // 獨立 SVG／PNG 無法繼承頁面 CSS。輸出時解析 token，色值仍只在 CSS 手寫一次。
  function svg(element: ReactElement) {
    return renderToStaticMarkup(element).replace(/var\((--[\w-]+)\)/g, (_, token: string) => {
      const value = tokens.get(token);
      if (!value) throw new Error(`Missing brand asset token: ${token}`);
      return value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;");
    });
  }

  async function writeAsset(path: string, content: string | Buffer) {
    const output = `public${path}`;
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, typeof content === "string" ? `<!-- Generated by npm run generate:brand; do not edit. -->\n${content}\n` : content);
  }

  const icon = svg(
    <svg xmlns="http://www.w3.org/2000/svg" width="180" height="180" viewBox="0 0 36 36" role="img" aria-label={SITE_NAME}>
      <rect width="36" height="36" fill="var(--brand-cream)" />
      <g transform="translate(2 2)" aria-hidden="true"><BrandMark variant="compact" width={32} height={32} /></g>
    </svg>,
  );
  await writeAsset(FAVICON_PATH, icon);
  await writeAsset(APPLE_TOUCH_ICON_PATH, await sharp(Buffer.from(icon)).png().toBuffer());

  const share = svg(
    <svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630" role="img" aria-label={BRAND_IMAGE_ALT}>
      <rect width="1200" height="630" fill="var(--brand-cream)" />
      <path d="M740 80v470" stroke="var(--brand-outline)" strokeWidth="2" />
      <g fill="var(--brand-ink)" fontFamily="var(--sans)">
        <text x="80" y="210" fontSize="88" fontWeight="700">{SITE_NAME}</text>
        <text x="84" y="266" fontSize="30">{SITE_ROMANIZATION}</text>
        <text x="80" y="392" fontSize="36" fontWeight="700">{BRAND_PROMISE}</text>
        <text x="80" y="450" fontSize="26">{SITE_PURPOSE}</text>
      </g>
      <g transform="translate(825 95)" aria-hidden="true"><BrandMark variant="full" width={230} height={440} /></g>
    </svg>,
  );
  await writeAsset(OG_IMAGE_PATH, share);
}

generateBrandAssets().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
